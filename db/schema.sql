-- PostgreSQL schema for primvmon_zoho_vendors, converted from the MariaDB 11.4
-- phpMyAdmin dump. Identifiers are lowercased so queries need no double quotes
-- (MySQL `Zoho_Id` -> zoho_id). Keys and indexes live in indexes.sql and are
-- created after the data load.
--
-- Type mapping: tinyint -> smallint, unsigned int -> bigint, datetime/timestamp
-- -> timestamp, enum -> varchar + CHECK. MySQL "ON UPDATE current_timestamp()"
-- has no column-level equivalent in Postgres and is dropped.

-- App / auth tables (vendor-search web app login) -----------------------------

CREATE TABLE app_auth_log (
  id      bigint GENERATED BY DEFAULT AS IDENTITY,
  at      timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  event   varchar(40) NOT NULL,
  email   varchar(190),
  ip      varchar(45),
  detail  varchar(255)
);

CREATE TABLE app_otp_codes (
  email           varchar(190) NOT NULL,
  code_hash       char(64) NOT NULL,
  expires_at      timestamp NOT NULL,
  cooldown_until  timestamp NOT NULL,
  attempts        smallint NOT NULL DEFAULT 0,
  created_at      timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE app_rate_limits (
  rl_key        varchar(120) NOT NULL,
  hits          bigint NOT NULL DEFAULT 0,
  window_start  timestamp NOT NULL
);

CREATE TABLE app_sessions (
  id            char(64) NOT NULL,
  email         varchar(190) NOT NULL,
  created_at    timestamp NOT NULL,
  last_seen_at  timestamp NOT NULL,
  expires_at    timestamp NOT NULL,
  ip            varchar(45),
  user_agent    varchar(255)
);

CREATE TABLE app_settings (
  k           varchar(64) NOT NULL,
  v           text,
  updated_at  timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE app_users (
  email        varchar(190) NOT NULL,
  note         varchar(120),
  added_by     varchar(190),
  added_at     timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  disabled_at  timestamp
);

