-- Service-area rules per vendor and task type (Dumpster, Porta Potty, ...).
-- Zone_*_Range is a "low,high" mileage band; *_Zipcodes_Serviced and County_*
-- are comma-separated lists.
CREATE TABLE vendor_zoning (
  id                                              integer GENERATED BY DEFAULT AS IDENTITY,
  zoho_zoning_id                                  varchar(255) NOT NULL,
  vendor_id                                       varchar(255) NOT NULL,
  task_type                                       text,
  zone_data_active                                smallint DEFAULT 0,
  service_area_map                                text,
  services_term                                   varchar(255),
  service_by                                      varchar(255),
  zone_a_range                                    varchar(50),
  zone_b_range                                    varchar(50),
  zone_c_range                                    varchar(50),
  zone_a_up_charge                                varchar(50),
  zone_b_up_charge                                varchar(50),
  zone_c_up_charge                                varchar(50),
  zone_a_zipcodes_serviced                        text,
  zone_b_zipcodes_serviced                        text,
  zone_c_zipcodes_serviced                        text,
  county_a                                        text,
  county_b                                        text,
  county_c                                        text,
  alternative_service_by_documented_on_zone_form  text,
  mass_update                                     varchar(255),
  check_field                                     varchar(255),
  created_at                                      timestamp DEFAULT CURRENT_TIMESTAMP,
  updated_at                                      timestamp DEFAULT CURRENT_TIMESTAMP,
  is_deleted                                      smallint NOT NULL DEFAULT 0,
  deleted_at                                      timestamp,
  deletion_source                                 varchar(50),
  cross_state_line                                varchar(10),
  states_serviced                                 text
);

-- Precomputed (OSRM) driving distance from each vendor to each zip code.
CREATE TABLE vendor_zip_driving_distance (
  id               bigint GENERATED BY DEFAULT AS IDENTITY,
  vendor_id        varchar(100) NOT NULL,
  zip_code         varchar(10) NOT NULL,
  driving_miles    numeric(8,2) NOT NULL,
  driving_minutes  integer NOT NULL,
  straight_miles   numeric(8,2) NOT NULL,
  last_updated     timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Background job bookkeeping for filling vendor_zip_driving_distance.
CREATE TABLE vendor_cache_log (
  vendor_id       varchar(100) NOT NULL,
  status          varchar(10) NOT NULL DEFAULT 'pending'
                  CHECK (status IN ('pending', 'processing', 'complete', 'error')),
  zips_processed  bigint NOT NULL DEFAULT 0,
  last_run        timestamp,
  error_message   text,
  created_at      timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at      timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  zips_total      bigint NOT NULL DEFAULT 0,
  pid             bigint,
  started_at      timestamp
);

CREATE TABLE vendor_cache_queue (
  vendor_id     varchar(100) NOT NULL,
  requested_at  timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  processed     smallint NOT NULL DEFAULT 0,
  priority      smallint NOT NULL DEFAULT 0
);

-- Geography -------------------------------------------------------------------

-- US zip code -> lat/lng centroid; used to geocode the customer's zip.
CREATE TABLE zip_centroids (
  zip_code  varchar(10) NOT NULL,
  lat       numeric(9,6) NOT NULL,
  lng       numeric(9,6) NOT NULL,
  state     char(2) NOT NULL,
  city      varchar(100) NOT NULL DEFAULT ''
);

-- Customer zips searched that had no centroid (logged by the search API).
CREATE TABLE missing_zip_centroids (
  zip_code        varchar(10) NOT NULL,
  searched_count  integer NOT NULL DEFAULT 1,
  first_seen      timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_seen       timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  resolved        smallint NOT NULL DEFAULT 0
);
